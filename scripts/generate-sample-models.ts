/**
 * Bakes the illustrative sample GLB models (with named component meshes and
 * component metadata in node extras) into public/models/.
 *   npm run gen:models
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { GLTFExporter } from 'three/examples/jsm/exporters/GLTFExporter.js';
import { formulaCar } from '../src/three/models/procedural/vehicles';
import { radialEngine } from '../src/three/models/procedural/machines';
import { brain } from '../src/three/models/procedural/biology';
import type { CatalogEntry } from '../src/types';

// GLTFExporter uses FileReader to assemble binary output – minimal Node polyfill.
class NodeFileReader {
  result: ArrayBuffer | string | null = null;
  onloadend: (() => void) | null = null;
  readAsArrayBuffer(blob: Blob) {
    blob.arrayBuffer().then((b) => {
      this.result = b;
      this.onloadend?.();
    });
  }
  readAsDataURL(blob: Blob) {
    blob.arrayBuffer().then((b) => {
      this.result = `data:${blob.type};base64,${Buffer.from(b).toString('base64')}`;
      this.onloadend?.();
    });
  }
}
(globalThis as unknown as { FileReader: unknown }).FileReader = NodeFileReader;

const out = join(import.meta.dirname, '..', 'public', 'models');
mkdirSync(out, { recursive: true });

const samples = [
  { arch: formulaCar, file: 'f1-car.glb', id: 'f1-car', keywords: ['formula 1 car', 'f1 car', 'race car', 'racing car', 'racer', 'hot wheels f1', 'formula one', 'open wheel race car', 'toy formula 1 car'] },
  { arch: radialEngine, file: 'radial-engine.glb', id: 'radial-engine', keywords: ['radial engine', 'aircraft engine', 'radial aircraft engine', 'piston aircraft engine'] },
  { arch: brain, file: 'human-brain.glb', id: 'human-brain', keywords: ['human brain', 'brain', 'brain model', 'anatomical brain model'] },
];

const exporter = new GLTFExporter();
const catalog: CatalogEntry[] = [];
for (const s of samples) {
  const group = s.arch.build();
  const glb = (await exporter.parseAsync(group, { binary: true })) as ArrayBuffer;
  writeFileSync(join(out, s.file), Buffer.from(glb));
  console.log(`wrote ${s.file} (${(glb.byteLength / 1024).toFixed(0)} KB, ${group.children.length} components)`);
  catalog.push({
    id: s.id,
    name: s.arch.name,
    category: s.arch.category,
    subtitle: s.arch.subtitle,
    file: `/models/${s.file}`,
    keywords: s.keywords,
    license: 'CC0 – generated by HoloHand',
    attribution: 'HoloHand sample asset',
    note: 'Illustrative test asset with separately named component meshes – simplified geometry, not a measured reconstruction of any specific product.',
    source: 'Local catalog',
    archetype: s.arch.id,
  });
}
writeFileSync(join(out, 'catalog.json'), JSON.stringify({ version: 1, models: catalog }, null, 2));
console.log('wrote catalog.json');
